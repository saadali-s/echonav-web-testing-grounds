import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { KeyRound } from "lucide-react";

export interface ActivePin {
  id: string;
  codeMasked: string;
  generatedBy: string;
  timeRemaining: string;
  status: "AWAITING_DEVICE" | "CONSUMED" | "EXPIRED";
}

export function ActivePinsTable({ pins }: { pins: ActivePin[] }) {
  return (
    <Card className="h-full flex flex-col rounded-xl border-2 border-zinc-950 dark:border-zinc-800 shadow-[4px_4px_0px_0px_rgba(24,24,27,1)] dark:shadow-none bg-white dark:bg-zinc-950 overflow-hidden">
      <CardHeader className="border-b-2 border-zinc-950 dark:border-zinc-800 bg-zinc-50/50 dark:bg-zinc-900/50 pb-4 p-5">
        <CardTitle className="font-black uppercase tracking-wider text-sm">Active Provisioning Requests</CardTitle>
      </CardHeader>
      
      <CardContent className="flex-1 p-0 overflow-y-auto">
        {pins.length === 0 ? (
          <div className="h-full flex flex-col items-center justify-center p-8 text-center bg-zinc-50/50 dark:bg-zinc-950">
            <div className="w-16 h-16 rounded-xl border-2 border-zinc-300 dark:border-zinc-700 flex items-center justify-center bg-white dark:bg-zinc-900 mb-4 -rotate-3">
              <KeyRound className="h-8 w-8 text-zinc-400 dark:text-zinc-600" />
            </div>
            <p className="font-black text-lg text-zinc-950 dark:text-zinc-100 uppercase tracking-tight">No Active PINs.</p>
            <p className="text-xs font-bold text-zinc-500 mt-2 max-w-sm uppercase tracking-widest leading-relaxed">Generated PINs will appear here until they expire or are consumed.</p>
          </div>
        ) : (
          <div className="min-w-[500px]">
            <div className="grid grid-cols-[1fr_1.5fr_1fr_1fr] gap-4 px-6 py-4 border-b-2 border-zinc-950 dark:border-zinc-800 bg-zinc-100/50 dark:bg-zinc-900 text-[11px] font-black text-zinc-600 dark:text-zinc-400 uppercase tracking-wider sticky top-0">
              <span>PIN Code</span>
              <span>Generated By</span>
              <span>Time Remaining</span>
              <span className="text-right">Status</span>
            </div>
            <div className="flex flex-col">
              {pins.map((pin, index) => {
                const isLast = index === pins.length - 1;
                const isConsumed = pin.status === "CONSUMED";
                
                return (
                  <div key={pin.id} className={`grid grid-cols-[1fr_1.5fr_1fr_1fr] gap-4 px-6 py-5 items-center hover:bg-zinc-50 dark:hover:bg-zinc-900/50 transition-colors ${!isLast ? 'border-b-2 border-zinc-100 dark:border-zinc-800' : ''} ${isConsumed ? 'opacity-50 grayscale' : ''}`}>
                    <div>
                        <span className="font-mono text-sm font-black text-zinc-950 dark:text-zinc-100 tracking-widest bg-zinc-100 dark:bg-zinc-800 border-2 border-zinc-950 dark:border-zinc-700 px-2.5 py-1.5 rounded-md shadow-[2px_2px_0px_0px_rgba(24,24,27,1)] dark:shadow-none inline-flex">
                            {pin.codeMasked}
                        </span>
                    </div>
                    <span className="text-xs font-bold text-zinc-950 dark:text-zinc-100 uppercase">{pin.generatedBy}</span>
                    <span className="font-mono text-xs font-black text-zinc-950 dark:text-zinc-100 bg-amber-100 dark:bg-amber-900/40 px-2 py-1 rounded border-2 border-zinc-950 dark:border-amber-900/50 inline-flex w-fit">{pin.timeRemaining}</span>
                    <div className="text-right">
                      <Badge 
                        variant={pin.status === "AWAITING_DEVICE" ? "outline" : "secondary"} 
                        className={`text-[10px] font-black uppercase tracking-wider border-2 ${pin.status === "AWAITING_DEVICE" ? "border-zinc-950 text-zinc-950 dark:border-zinc-100 dark:text-zinc-100 bg-transparent shadow-[2px_2px_0px_0px_rgba(24,24,27,1)] dark:shadow-none" : "border-zinc-200 dark:border-zinc-800 bg-zinc-100 dark:bg-zinc-800 text-zinc-500"}`}
                      >
                        {pin.status.replace("_", " ")}
                      </Badge>
                    </div>
                  </div>
                );
              })}
            </div>
          </div>
        )}
      </CardContent>
    </Card>
  );
}