"use client";

import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Trash2, UserCog2 } from "lucide-react";

export interface InvitedUsers {
  id: string;
  name: string;
  email: string;
  pin: string;
  generatedBy: string;
  invitedDate: string;
}

interface InvitedUserListProps {
  users: InvitedUsers[];
  onDelete: (id: string) => void;
}

export function InvitedUsersList({ users, onDelete }: InvitedUserListProps) {
  return (
    <Card className="h-full flex flex-col rounded-xl border-2 border-zinc-950 dark:border-zinc-800 shadow-[4px_4px_0px_0px_rgba(24,24,27,1)] dark:shadow-none bg-white dark:bg-zinc-950 overflow-hidden">
      <CardHeader className="border-b-2 border-zinc-950 dark:border-zinc-800 bg-blue-400 dark:bg-blue-950/40 py-5">
        <CardTitle className="font-black uppercase tracking-widest text-sm flex items-center gap-3 text-blue-950 dark:text-blue-500">
          <UserCog2 className="h-5 w-5" />
          View Invited Users
        </CardTitle>
      </CardHeader>

      <CardContent className="p-0 overflow-x-auto flex-1">
        <div className="min-w-[700px]">
          <div className="grid grid-cols-[1.2fr_1.5fr_1fr_1.5fr_1fr_80px] gap-4 px-6 py-4 border-b-2 border-zinc-950 dark:border-zinc-800 text-xs font-black text-zinc-700 dark:text-zinc-300 uppercase tracking-widest bg-zinc-50/50 dark:bg-zinc-900/50">
            <span>Name</span>
            <span>Email</span>
            <span>Pairing Pin</span>
            <span>Generated By</span>
            <span className="text-right">Invited On</span>
            <span className="text-center">Remove</span>
          </div>

          <div className="flex flex-col">
            {users.length === 0 ? (
              <div className="px-6 py-8 text-center text-sm font-bold text-zinc-500 uppercase tracking-widest bg-zinc-50/30 dark:bg-zinc-900/30">
                No invited users found.
              </div>
            ) : (
              users.map((member, index) => {
                const isLast = index === users.length - 1;
                return (
                  <div
                    key={member.id}
                    className={`grid grid-cols-[1.2fr_1.5fr_1fr_1.5fr_1fr_80px] gap-4 px-6 py-5 items-center hover:bg-blue-50/50 dark:hover:bg-blue-950/20 transition-colors ${
                      !isLast
                        ? "border-b border-zinc-200 dark:border-zinc-800"
                        : ""
                    }`}
                  >
                    <span className="font-bold text-sm text-zinc-950 dark:text-zinc-100 truncate">
                      {member.name}
                    </span>
                    <span className="text-xs font-medium text-zinc-600 dark:text-zinc-400 truncate tracking-wide">
                      {member.email}
                    </span>
                    <span className="text-xs font-mono font-bold text-zinc-700 dark:text-zinc-300">
                      {member.pin}
                    </span>
                    <span className="text-xs font-mono font-bold text-zinc-700 dark:text-zinc-300 truncate">
                      {member.generatedBy}
                    </span>
                    <span className="text-xs font-bold text-zinc-500 dark:text-zinc-400 text-right uppercase tracking-wider">
                      {member.invitedDate}
                    </span>

                    <div className="flex justify-center">
                      <button
                        onClick={() => onDelete(member.id)}
                        className="p-2 text-zinc-400 hover:text-zinc-900 dark:hover:text-zinc-100 hover:bg-red-400 dark:hover:bg-red-500 rounded-md transition-colors focus:outline-none focus:ring-2 focus:ring-zinc-500"
                        title="Delete User"
                      >
                        <Trash2 className="h-5 w-5" />
                      </button>
                    </div>
                  </div>
                );
              })
            )}
          </div>
        </div>
      </CardContent>
    </Card>
  );
}
